// 为单元独立编写的短篇阅读；场景和人物均为练习设定。
export interface N5ReadingQuestion {
  id: string
  prompt: string
  options: string[]
  correctIndex: number
  explanation: string
}
export interface N5CourseReading {
  unitId: string
  title: string
  text: string
  reading: string
  chinese: string
  questions: N5ReadingQuestion[]
}

type Question = [string, string[], number, string]
function reading(unitId: string, title: string, text: string, kana: string, chinese: string, questions: Question[]): N5CourseReading {
  return { unitId, title, text, reading: kana, chinese, questions: questions.map(([prompt, options, correctIndex, explanation], index) => ({ id: `${unitId}_reading_${index + 1}`, prompt, options, correctIndex, explanation })) }
}

