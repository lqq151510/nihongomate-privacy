/** N5 原创补充练习；场景虚构。听力朗读使用设备语音合成。 */
export interface N5ExtraQuestion { id: string; prompt: string; options: string[]; correctIndex: number; explanation: string }
export interface N5CoursePracticeExtra {
  unitId: string
  listening: { title: string; situation: string; lines: { speaker: string; japanese: string; reading: string; chinese: string }[]; questions: N5ExtraQuestion[] }
  reading: { title: string; text: string; reading: string; chinese: string; questions: N5ExtraQuestion[] }
}
type Q = [prompt: string, options: string[], correctIndex: number, explanation: string]
type Line = [speaker: string, japanese: string, reading: string, chinese: string]
function practice(unitId: string, title: string, situation: string, lines: Line[], listenQ: Q[], readingTitle: string, text: string, kana: string, chinese: string, readingQ: Q[]): N5CoursePracticeExtra {
  const questions = (kind: string, items: Q[]) => items.map(([prompt, options, correctIndex, explanation], i) => ({ id: `${unitId}_extra_${kind}_${i + 1}`, prompt, options, correctIndex, explanation }))
  return { unitId, listening: { title, situation, lines: lines.map(([speaker, japanese, reading, translation]) => ({ speaker, japanese, reading, chinese: translation })), questions: questions('listening', listenQ) }, reading: { title: readingTitle, text, reading: kana, chinese, questions: questions('reading', readingQ) } }
}

