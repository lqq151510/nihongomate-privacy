import type { ListeningDialogue } from './listeningScenarios'

type Speaker = { name: string; role: ListeningDialogue['sentences'][number]['role'] }
type Line = [japanese: string, furigana: string, chinese: string]

function dialogue(
  id: string, level: ListeningDialogue['level'], title: string, scene: string,
  speakers: [Speaker, Speaker], lines: Line[], question: string, options: string[],
  correctAnswer: number, explanation: string,
): ListeningDialogue {
  return {
    id, level, title, scene: `练习场景 · ${scene}`,
    sentences: lines.map(([japanese, furigana, chinese], index) => ({ speaker: speakers[index % 2].name, role: speakers[index % 2].role, japanese, furigana, chinese })),
    comprehensionQuestion: { question, options, correctAnswer, explanation },
  }
}

