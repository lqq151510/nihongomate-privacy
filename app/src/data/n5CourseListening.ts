/**
 * N5 入门课程原创听力文稿。音频由设备日语语音合成引擎提供；
 * 假名是朗读辅助，不代表人工录音、词汇音调标注或发音已逐条审校。
 * 场景、人物及安排均为语言练习，并非现实服务指南。
 */
export interface N5ListeningLine {
  speaker: string
  japanese: string
  reading: string
  chinese: string
}

export interface N5CourseListening {
  unitId: string
  title: string
  situation: string
  lines: N5ListeningLine[]
  question: {
    prompt: string
    options: string[]
    correctIndex: number
    explanation: string
  }
}

type Line = [speaker: string, japanese: string, reading: string, chinese: string]
function lesson(
  unitId: string, title: string, situation: string, lines: Line[],
  prompt: string, options: string[], correctIndex: number, explanation: string,
): N5CourseListening {
  return { unitId, title, situation, lines: lines.map(([speaker, japanese, reading, chinese]) => ({ speaker, japanese, reading, chinese })), question: { prompt, options, correctIndex, explanation } }
}

